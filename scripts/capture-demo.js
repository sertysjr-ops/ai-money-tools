#!/usr/bin/env node
/**
 * capture-demo — regenerate the marketing site's terminal replay from
 * REAL live tool runs.
 *
 * Runs three showcase commands against the local Ollama model, captures
 * stdout, and rewrites the SCRIPT array inside marketing/site.html
 * (between the DEMO-SCRIPT markers) so the landing-page demo never
 * drifts from what the tools actually output today.
 *
 * Usage: node scripts/capture-demo.js          (rewrites site.html)
 *        node scripts/capture-demo.js --check  (exit 1 if site.html is stale)
 */
const { execFileSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SITE = path.join(ROOT, "marketing", "site.html");
const START = "/* DEMO-SCRIPT:START";
const END = "/* DEMO-SCRIPT:END */";

const STORY = [
  "I spent six months building a SaaS in complete silence. No posts, no",
  "updates, no audience. Launch day came and exactly four people signed up.",
  "Two of them were my friends. The mistake wasn't the product, it was the",
  "silence. When I started sharing progress publicly, feedback flooded in",
  "daily and the roadmap wrote itself. The first paying customer came from",
  "a reply to one of my posts, not from an ad. Build in public isn't",
  "marketing. It's product development with witnesses.",
].join(" ");

// [displayed command, argv for node, stdin]
const SHOWCASE = [
  [
    'echo "building apps with local AI" | hookline --count 3',
    ["tools/hookline/cli.js", "--count", "3"],
    "building apps with local AI\n",
  ],
  [
    "cat story.md | threadsmith --tweets 4",
    ["tools/threadsmith/cli.js", "--tweets", "4"],
    STORY + "\n",
  ],
  [
    'pitchforge offer.txt --target "indie newsletter writers" --count 2',
    ["tools/pitchforge/cli.js", "--target", "indie newsletter writers", "--count", "2"],
    "I build offline AI writing tools for content creators.\n",
  ],
];

const MAX_LINE = 300; // full tweets (≤280) survive; only pathological lines clip

function runLive(argv, stdin) {
  const out = execFileSync(process.execPath, argv, {
    cwd: ROOT,
    input: stdin,
    encoding: "utf8",
    timeout: 180_000,
    env: { ...process.env },
  });
  return out
    .split("\n")
    .map((l) => l.trimEnd())
    .filter((l) => l.trim().length > 0)
    .map((l) => (l.length > MAX_LINE ? l.slice(0, MAX_LINE - 1) + "…" : l));
}

function buildScript() {
  const steps = [];
  SHOWCASE.forEach(([cmd, argv, stdin], idx) => {
    if (idx > 0) steps.push({ t: "gap" });
    steps.push({ t: "cmd", s: cmd });
    console.error(`▸ capturing: ${cmd}`);
    const lines = runLive(argv, stdin);
    if (lines.length === 0) throw new Error(`no output from: ${cmd}`);
    for (const s of lines) steps.push({ t: "out", s });
  });
  return steps;
}

function render(steps) {
  const lines = steps.map((st) => {
    if (st.t === "gap") return `  { t: "gap" },`;
    return `  { t: "${st.t}",  s: ${JSON.stringify(st.s)} },`;
  });
  return `const SCRIPT = [\n${lines.join("\n")}\n];`;
}

function extractBlock(html) {
  const i0 = html.indexOf(START);
  const i1 = html.indexOf(END);
  if (i0 === -1 || i1 === -1) return null;
  return { i0, i1 };
}

function main() {
  const check = process.argv.includes("--check");
  const html = fs.readFileSync(SITE, "utf8");
  const loc = extractBlock(html);
  if (!loc) {
    console.error("DEMO-SCRIPT markers not found in site.html");
    process.exit(2);
  }

  // --check is structural, not byte-identical: the model is non-deterministic,
  // so "freshness" can't mean "same output". It means: the block is valid JS
  // with at least one command that has at least one output line.
  if (check) {
    const block = html.slice(loc.i0, loc.i1);
    const m = block.match(/const SCRIPT = (\[[\s\S]*\]);/);
    if (!m) {
      console.error("site.html demo: SCRIPT array not parseable");
      process.exit(1);
    }
    let steps;
    try {
      steps = eval(m[1]); // it's our own generated literal
    } catch (e) {
      console.error("site.html demo: SCRIPT literal broken:", e.message);
      process.exit(1);
    }
    const cmds = steps.filter((s) => s.t === "cmd").length;
    const outs = steps.filter((s) => s.t === "out").length;
    if (cmds < 1 || outs < cmds) {
      console.error(`site.html demo: ${cmds} cmds / ${outs} outs — too thin`);
      process.exit(1);
    }
    console.log(`site.html demo OK (${cmds} commands, ${outs} output lines)`);
    return;
  }

  const steps = buildScript();
  const block =
    START + " — regenerated by scripts/capture-demo.js, do not hand-edit */\n" +
    render(steps) +
    "\n" + END;
  const next = html.slice(0, loc.i0) + block + html.slice(loc.i1 + END.length);
  fs.writeFileSync(SITE, next);
  console.error(`✓ site.html demo regenerated (${steps.length} steps, live output)`);
}

main();
